#!/usr/bin/env python3
"""Generate the embedded 2025 demand and production constants in DatosOperativos.java."""
import csv
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEMAND = ROOT / "demanda" / "demanda - Sheet1.csv"
PROD = ROOT / "produccion" / "prod.csv"
OUT = ROOT / "tools" / "DatosOperativos.java"
MONTHS = ["Ene.", "Feb.", "Mar.", "Abr.", "May.", "Jun.", "Jul.", "Ago.", "Sept.", "Oct.", "Nov.", "Dic."]
DAYS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]
CHANNELS = ["MAXICONSUMO", "GRANDES CLIENTES", "RED PROPIA"]
PRODUCT_RUBROS = [
    ["LAVANDINA COMUN", "LAVANDINA CONCENTRADA"],
    ["LIQUIDO DESINFECTANTE"],
    ["LAVAVAJILLA"],
    ["LIQUIDO LAVAR ROPA"],
    ["SUAVIZANTE"],
    ["DETERGENTE CONCENTRADO"],
]
PRODUCT_NAMES = ["Lavandina", "Desinfectante", "Lavavajilla", "Lavarropa", "Suavizante", "Detergente concentrado"]


def num(s):
    try:
        return float((s or "").strip().replace(".", "").replace(",", "."))
    except ValueError:
        return 0.0


def java_double(x):
    return format(float(x), ".12g") + ("" if "e" in format(float(x), ".12g").lower() and "." in format(float(x), ".12g") else "")


def main():
    monthly_pedidos = [[[0.0 for _ in MONTHS] for _ in PRODUCT_NAMES] for _ in CHANNELS]
    with DEMAND.open(encoding="utf-8-sig", newline="") as f:
        rows = csv.DictReader(f)
        for row in rows:
            if row.get("Año") != "2025":
                continue
            channel = (row.get("VentasXnegocio") or "").strip().upper()
            if channel not in CHANNELS:
                continue
            month = (row.get("Mes") or "").strip()
            if month not in MONTHS:
                continue
            for product, rubros in enumerate(PRODUCT_RUBROS):
                if row.get("RubroDes") in rubros:
                    monthly_pedidos[CHANNELS.index(channel)][product][MONTHS.index(month)] += num(row.get("Pedidos"))

    # Rate per family is pooled across mapped product rubros; September is excluded.
    production = [0.0] * len(PRODUCT_NAMES)
    elapsed = [0.0] * len(PRODUCT_NAMES)
    with PROD.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f, delimiter=";"):
            if row.get("RtoMes") not in MONTHS[:8]:
                continue
            for product, rubros in enumerate(PRODUCT_RUBROS):
                if row.get("RubroDes") in rubros:
                    production[product] += num(row.get("Cajas"))
                    elapsed[product] += num(row.get("Tiempo"))
    hours_open = 8.0 * 365.0 / 12.0 * 24.0
    active_rates = [production[i] / (elapsed[i] / 60.0) if elapsed[i] else 0.0 for i in range(len(PRODUCT_NAMES))]
    effective_rates = [production[i] / hours_open for i in range(len(PRODUCT_NAMES))]
    operation_fractions = [(elapsed[i] / 60.0) / hours_open for i in range(len(PRODUCT_NAMES))]

    lines = [
        "/** Generated by generar_datos_operativos.py; do not edit this file manually. */",
        "public final class DatosOperativos {",
        "    public static final int CANALES = 3;",
        "    public static final int PRODUCTOS = 6;",
        "    private static final int[] DIAS = new int[] {" + ", ".join(map(str, DAYS)) + "};",
        "    private static final String[] NOMBRES_CANALES = new String[] {" + ", ".join('"'+x+'"' for x in CHANNELS) + "};",
        "    private static final String[] NOMBRES_PRODUCTOS = new String[] {" + ", ".join('"'+x+'"' for x in PRODUCT_NAMES) + "};",
        "    // Tasas mensuales cajas/semana; un mes sin pedidos se representa por cero.",
        "    private static final double[][][] MENSUAL = new double[][][] {",
    ]
    for c in range(len(CHANNELS)):
        lines.append("        {")
        for p in range(len(PRODUCT_NAMES)):
            weekly = [monthly_pedidos[c][p][m] / DAYS[m] * 7.0 for m in range(12)]
            lines.append("            {" + ", ".join(java_double(x) for x in weekly) + "},")
        lines.append("        },")
    lines += ["    };", "    private static final double[] RATES_EFECTIVOS = new double[] {" + ", ".join(java_double(x) for x in effective_rates) + "};",
        "    private static final double[] RATES_ACTIVOS = new double[] {" + ", ".join(java_double(x) for x in active_rates) + "};",
        "    private static final double[] FRACCIONES_OPERACION = new double[] {" + ", ".join(java_double(x) for x in operation_fractions) + "};", "",
        "    private DatosOperativos() {}", "",
        "    /** Media anual cajas/semana, ponderada por días de cada mes. Devuelve copia. */",
        "    public static double[][] medias() { return estadistico(false); }", "",
        "    /** Desvío poblacional ponderado por días de cada mes. Devuelve copia. */",
        "    public static double[][] desvios() { return estadistico(true); }", "",
        "    private static double[][] estadistico(boolean desvio) {",
        "        double[][] out = new double[CANALES][PRODUCTOS];",
        "        for (int c = 0; c < CANALES; c++) for (int p = 0; p < PRODUCTOS; p++) {",
        "            double mean = 0.0;",
        "            for (int m = 0; m < 12; m++) mean += MENSUAL[c][p][m] * DIAS[m] / 365.0;",
        "            if (!desvio) out[c][p] = mean;",
        "            else {",
        "                double variance = 0.0;",
        "                for (int m = 0; m < 12; m++) { double d = MENSUAL[c][p][m] - mean; variance += DIAS[m] / 365.0 * d * d; }",
        "                out[c][p] = Math.sqrt(variance);",
        "            }",
        "        }",
        "        return out;",
        "    }", "",
        "    /** Throughput histórico por hora de apertura, ene-ago (8 x 365/12 x 24 = 5840 h); año de producción desconocido. No es capacidad mecánica máxima. Devuelve copia. */",
        "    public static double[] rates() { return RATES_EFECTIVOS.clone(); }",
        "    /** Tasa observada durante tiempo registrado: Cajas/(Tiempo/60), ene-ago. Devuelve copia. */",
        "    public static double[] ratesActivos() { return RATES_ACTIVOS.clone(); }",
        "    /** Fracción de las horas de apertura representada por Tiempo (si Tiempo son minutos). Devuelve copia. */",
        "    public static double[] fraccionesOperacion() { return FRACCIONES_OPERACION.clone(); }", "",
        "    public static String canalNombre(int canal) { validarCanal(canal); return NOMBRES_CANALES[canal]; }",
        "    public static String productoNombre(int producto) { validarProducto(producto); return NOMBRES_PRODUCTOS[producto]; }", "",
        "    static double tasaMensual(int canal, int producto, int mes) {",
        "        validarCanal(canal); validarProducto(producto); if (mes < 0 || mes >= 12) throw new IllegalArgumentException(\"mes fuera de rango\");",
        "        return MENSUAL[canal][producto][mes];",
        "    }", "",
        "    /** Bootstrap de la tasa semanal de pedidos del mes compartido por un bloque de 4 semanas. */",
        "    public static double demanda(long seed, int canal, int producto, long semana, double media, double desvio) {",
        "        validarCanal(canal); validarProducto(producto);",
        "        if (!finito(media) || !finito(desvio) || desvio < 0.0) throw new IllegalArgumentException(\"media finita y desvio finito no negativo requeridos\");",
        "        int mes = mesSeleccionado(seed, semana);",
        "        double base = MENSUAL[canal][producto][mes];",
        "        double histMean = medias()[canal][producto];",
        "        double histSd = desvios()[canal][producto];",
        "        // Históricos por defecto se preservan exactamente y no se recortan.",
        "        if (Double.compare(media, histMean) == 0 && Double.compare(desvio, histSd) == 0) return base;",
        "        double ajustada = histSd == 0.0 ? media : (base - histMean) * desvio / histSd + media;",
        "        return Math.max(0.0, ajustada);",
        "    }", "",
        "    static int mesSeleccionado(long seed, long semana) {",
        "        double u = ComparacionEscenarios.uniforme(seed, 9, 0, semana / 4, 77);",
        "        int dia = (int) (u * 365.0);",
        "        int acumulado = 0;",
        "        for (int mes = 0; mes < 12; mes++) { acumulado += DIAS[mes]; if (dia < acumulado) return mes; }",
        "        return 11;",
        "    }", "",
        "    private static void validarCanal(int canal) { if (canal < 0 || canal >= CANALES) throw new IllegalArgumentException(\"canal fuera de rango\"); }",
        "    private static void validarProducto(int producto) { if (producto < 0 || producto >= PRODUCTOS) throw new IllegalArgumentException(\"producto fuera de rango\"); }",
        "    private static boolean finito(double d) { return !Double.isNaN(d) && !Double.isInfinite(d); }",
        "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("Wrote tools/DatosOperativos.java")


if __name__ == "__main__":
    main()
